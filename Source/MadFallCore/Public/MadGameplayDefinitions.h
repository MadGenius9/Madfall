/** Tools and weapons. */
struct MADFALLCORE_API FMadToolStats
{
	/** Damage type -> hit points per use, e.g. "madfall:blunt": 25. */
	TMap<FName, float> Damage;

	/** Matched against a block's harvest tool_tags. A matching tool deals full damage and harvests drops. */
	TArray<FName> HarvestTags;

	/** Must be >= a block's harvest tier to harvest its drops. */
	int32 Tier = 0;

	/** Uses before breaking. 0 = unbreakable. */
	int32 Durability = 0;

	/** Seconds between uses. */
	float UseSeconds = 0.6f;

	float StaminaCost = 2.0f;

	/** Reach in voxels. */
	float Range = 4.0f;

	int32 ModSlots = 0;

	/** Items consumed by one repair action, and the fraction of max durability it restores. */
	TArray<FMadItemAmount> RepairWith;
	float RepairFraction = 0.25f;

	/** Ranged weapons: the item each shot uses up. NAME_None for melee. */
	FName Ammo;

	/** Launch speed, voxels per second. */
	float ProjectileSpeed = 45.0f;

	/** Fraction of normal gravity a shot falls with. */
	float ProjectileGravity = 0.5f;

	/** Chance a shot that hits the world can be picked up again. */
	float RecoverChance = 0.5f;

	bool IsRanged() const { return !Ammo.IsNone(); }
};

