/**
 * A zombie variant.
 *
 * Variants are data, not subclasses: a brute is a civilian with more health,
 * more block damage and a bigger scale. Spawn groups are memberships listed on
 * the variant, so a mod adds a zombie to POI spawns or hordes by naming the
 * group, without touching the prefab or the director.
 */
struct MADFALLCORE_API FMadZombieDefinition
{
	FName Id;
	FString DisplayName;
	TArray<FName> Tags;

	/** e.g. "madfall:zombies/civilian", "madfall:zombies/horde". */
	TArray<FName> SpawnGroups;
	float SpawnWeight = 1.0f;
	int32 MinGameStage = 0;

	float Health = 100.0f;

	/** Metres per second. */
	float WalkSpeed = 1.4f;
	float RunSpeed = 3.2f;

	float AttackDamage = 8.0f;

	/** Hit points dealt to a block per attack while digging. */
	float BlockDamage = 20.0f;
	float AttackSeconds = 1.2f;
	FName DamageType = FName(TEXT("madfall:blunt"));

	/** Infection added to the player per landed hit. */
	float InfectionPerHit = 3.0f;

	/** Voxels. */
	float SightRange = 24.0f;
	float HearingRange = 40.0f;

	int32 Experience = 25;
	FName LootTable;

	float Scale = 1.0f;
	/** Skin colour, linear (authored as sRGB in appearance.tint). */
	FLinearColor Tint = FLinearColor(0.10f, 0.17f, 0.07f);

	/** abilities.ranged: spits at a target it can see within RangedRange voxels. 0 damage = no ranged attack. */
	float RangedDamage = 0.0f;
	float RangedRange = 0.0f;
	float RangedSeconds = 3.0f;
	/** Voxels per second. */
	float RangedSpeed = 22.0f;

	/** abilities.scream: on sighting a target, alerts zombies within ScreamRadius voxels and calls ScreamSummons more. */
	float ScreamRadius = 0.0f;
	float ScreamSeconds = 45.0f;
	int32 ScreamSummons = 0;

	/** abilities.climbs_walls: climbs straight up any wall toward a target, like a ladder. */
	bool bClimbsWalls = false;

	/**
	 * Damage multipliers by damage type ("resistances"), as blocks have: 0.5
	 * takes half, 1.5 half again more, a type not listed 1. An armoured
	 * soldier shrugs off arrows; a bloater bursts on them.
	 */
	TMap<FName, float> Resistances;

	float GetDamageMultiplier(FName IncomingType) const
	{
		const float* Found = Resistances.Find(IncomingType);
		return Found != nullptr ? FMath::Max(0.0f, *Found) : 1.0f;
	}

	bool HasRanged() const { return RangedDamage > 0.0f && RangedRange > 0.0f; }
	bool HasScream() const { return ScreamRadius > 0.0f; }

	FName SourceModId;
	FString SourcePath;
};

/** How an animal reacts to the survivor. */
enum class EMadAnimalBehaviour : uint8
{
	/** Runs from a survivor it sees close by or hears, and from anything that hurts it. */
	Skittish,
	/** Grazes until hurt, then fights back until the survivor is out of reach. */
	Defensive,
	/** Hunts a survivor it sees. */
	Aggressive
};

/** When an animal is about. */
enum class EMadAnimalActivity : uint8
{
	Always,
	Day,
	Night
};

/**
 * Wildlife: something to hunt for meat and hide, and something that hunts back.
 *
 * A separate kind from zombies rather than a zombie variant: animals never dig,
 * never join a horde, spawn by biome instead of by POI group, and run away. What
 * they share with zombies - pathing, senses, a loot bag on death - is shared in
 * code, not in the schema.
 */
/**
 * An animated skeletal model an animal is drawn with (appearance.model), instead
 * of the figure built from its body proportions.
 *
 * WHY THE PATHS ARE DATA: the shipped deer and wolf come from one CC0 pack whose
 * clips are named per animal (DeerGallop, WolfAttack), and a mod's animal will
 * come from anywhere. Naming each clip's role keeps the rig from guessing, and
 * leaving a role out (a deer model with no attack clip, say)
 * just means that moment is not animated.
 */
struct MADFALLCORE_API FMadAnimalModel
{
	FSoftObjectPath Mesh;
	FSoftObjectPath Idle;
	FSoftObjectPath Walk;
	FSoftObjectPath Run;
	FSoftObjectPath Attack;
	FSoftObjectPath Hit;
	FSoftObjectPath Death;
	FSoftObjectPath Graze;

	/** Ground speed, m/s, at which the walk and run cycles play at their authored rate, so the feet keep pace. */
	float WalkCycleSpeed = 1.2f;
	float RunCycleSpeed = 6.0f;

	/** Degrees the model is turned about Z so its head points along the animal's forward (+X). */
	float Yaw = 0.0f;

	/** A mesh and the two clips an animal cannot do without. */
	bool IsSet() const { return !Mesh.IsNull() && !Idle.IsNull() && !Walk.IsNull(); }
};

