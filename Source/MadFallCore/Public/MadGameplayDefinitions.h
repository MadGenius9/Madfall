/** One rank of a perk: the level it unlocks at, and the stat multipliers it grants. */
struct MADFALLCORE_API FMadPerkRank
{
	int32 RequiredLevel = 1;

	/** Stat name -> multiplier applied while this rank is owned (ranks do not stack; the highest owned rank applies). */
	TMap<FName, float> Modifiers;

	/**
	 * Perk id -> rank of that perk the survivor must already own to buy this
	 * rank ("requires": { "madfall:athlete": 1 }). Per rank, not per perk, so a
	 * perk can open freely and gate only its top ranks - that is what makes a
	 * tree out of a flat list. Unknown perks, ranks a perk does not have and
	 * cycles are reported and removed at load, so no rank can be locked forever.
	 */
	TMap<FName, int32> Requires;
};

